function descriptionFor(seed: GameSeed): string {
  return (
    seed.description ??
    (CATEGORY_COPY[seed.category] ?? "Pilihan permainan untuk menemani " + "sesi bermainmu.") +
      " " +
      seed.name +
      " tersedia dari " +
      (VENDOR_NAMES[seed.vendor_id] ?? seed.vendor_id) +
      "."
  );
}

function createGame(seed: GameSeed): Game {
  const isLive = seed.category === "live";
  return {
    id: seed.id,
    vendor_id: seed.vendor_id,
    game_code: seed.game_code ?? seed.vendor_id + "/" + seed.id,
    name: seed.name,
    category: seed.category,
    min_bet: seed.min_bet ?? (isLive ? 500 : 100),
    max_bet: seed.max_bet ?? (isLive ? 500000 : 100000),
    status: "active",
    image_url: seed.image_url,
    rtp: seed.rtp ?? (isLive ? 0.973 : 0.962),
    description: descriptionFor(seed),
    is_new: seed.is_new ?? false,
    is_popular: seed.is_popular ?? false,
    is_featured: seed.is_featured ?? false,
    demo_supported: seed.demo_supported ?? !isLive,
  };
}

